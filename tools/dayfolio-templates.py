class LibraryError(Exception):
    """A library, an example or a gallery the generator will not guess about; the message names the file."""


def _load(name: str, file: str):
    """Another tool in this folder, as a module (once: dataclasses need it in sys.modules)."""
    if name not in sys.modules:
        spec = importlib.util.spec_from_file_location(name, Path(__file__).with_name(file))
        module = importlib.util.module_from_spec(spec)
        sys.modules[name] = module
        spec.loader.exec_module(module)
    return sys.modules[name]


def _build():
    return _load("dayfolio_build", "dayfolio-build.py")


def _archive():
    return _load("archive_page", "archive-page.py")


# ----- the library -----

@dataclass
class Option:
    key: str
    label: str
    color: str


@dataclass
class Field:
    key: str
    label: str
    type: str
    prompt: str = ""
    warning: bool = False
    carry_over: bool = False
    options: List[Option] = field(default_factory=list)


@dataclass
class Template:
    id: str
    pack: str                      # the pack that owns it, and so its page
    slug: str
    name: str
    cadence: str
    summary: str
    included_by_default: bool
    reminder: Optional[dict]
    fields: List[Field]
    source: str                    # the pack file, by name


@dataclass
class Pack:
    id: str
    name: str
    journal_name: str
    summary: str
    order: Optional[int]
    default_template: str
    own: List[Template]
    includes: List[str]
    source: str


class Library:
    def __init__(self, packs: List[Pack]):
        self.packs = packs
        self.templates: Dict[str, Template] = {t.id: t for p in packs for t in p.own}
        self.by_id = {p.id: p for p in packs}

    def listed(self, pack_id: str) -> List[Template]:
        """A pack's templates as the app lists them: its own, then the ones it includes (LibraryCatalog)."""
        pack = self.by_id[pack_id]
        return pack.own + [self.templates[i] for i in pack.includes]

    def packs_listing(self, template_id: str) -> List[Pack]:
        return [p for p in self.packs if any(t.id == template_id for t in self.listed(p.id))]

    def owner(self, template: Template) -> Pack:
        return self.by_id[template.pack]


def _need(data: dict, key: str, kind, where: str):
    if key not in data:
        raise LibraryError(f"{where}: '{key}' is missing")
    value = data[key]
    if not isinstance(value, kind) or isinstance(value, bool) and kind is not bool or value in ("", []):
        raise LibraryError(f"{where}: '{key}' is not what the pack format allows")
    return value


def _field(data: dict, where: str) -> Field:
    key = _need(data, "key", str, where)
    where = f"{where}: {key}"
    kind = _need(data, "type", str, where)
    if kind not in TYPE_NAMES:
        raise LibraryError(f"{where}: '{kind}' is not a field type")
    options = data.get("options", [])
    if kind in SELECTS and not options:
        raise LibraryError(f"{where}: a {TYPE_NAMES[kind]} field needs options")
    if kind not in SELECTS and options:
        raise LibraryError(f"{where}: only a select field has options")
    parsed, keys = [], set()
    for option in options:
        okey = _need(option, "key", str, where)
        color = _need(option, "color", str, f"{where}: {okey}")
        if okey in keys or color not in JOURNAL_COLORS + STATUS_COLORS:
            raise LibraryError(f"{where}: the option '{okey}' is repeated or has no colour the app knows")
        keys.add(okey)
        parsed.append(Option(okey, _need(option, "label", str, f"{where}: {okey}"), color))
    if data.get("presentation", "standard") not in ("standard", "warning"):
        raise LibraryError(f"{where}: '{data['presentation']}' is not a presentation")
    return Field(key, _need(data, "label", str, where), kind, data.get("prompt", ""),
                 data.get("presentation") == "warning", bool(data.get("carryOver")), parsed)


def _template(data: dict, pack_id: str, where: str) -> Template:
    tid = _need(data, "id", str, where)
    where = f"{where}: {tid}"
    if not tid.startswith(pack_id + ".") or not TAG.fullmatch(tid[len(pack_id) + 1:]):
        raise LibraryError(f"{where}: a template id is <pack-id>.<lowercase-with-hyphens>")
    cadence = _need(data, "cadence", str, where)
    if cadence not in CADENCES:
        raise LibraryError(f"{where}: '{cadence}' is not a cadence")
    reminder = data.get("reminder")
    if reminder is not None:
        days = reminder.get("weekdays")
        if (not isinstance(days, list) or not days or any(d not in DAYS for d in days)
                or not 0 <= reminder.get("hour", -1) <= 23 or not 0 <= reminder.get("minute", -1) <= 59):
            raise LibraryError(f"{where}: the reminder is not days 1–7, an hour and a minute")
    fields = [_field(f, where) for f in _need(data, "fields", list, where)]
    if len({f.key for f in fields}) != len(fields):
        raise LibraryError(f"{where}: two fields share a key")
    return Template(tid, pack_id, tid[len(pack_id) + 1:], _need(data, "name", str, where), cadence,
                    _need(data, "summary", str, where), bool(data.get("includedByDefault")), reminder, fields,
                    where.split(":")[0])


def load_library(folder: Path) -> Library:
    """Every pack in `folder`, checked the way the app's LibraryCatalog checks them, in the curated order."""
    files = sorted(folder.glob("*.json")) if folder.is_dir() else []
    if not files:
        raise LibraryError(f"{folder}: no packs; copy the app's in with --library /path/to/dayfolio")
    packs = []
    for file in files:
        try:
            data = json.loads(file.read_text(encoding="utf-8"))
        except json.JSONDecodeError as error:
            raise LibraryError(f"{file.name}: not JSON ({error})") from None
        if data.get("formatVersion") != 1 or not isinstance(data.get("pack"), dict):
            raise LibraryError(f"{file.name}: not a version 1 pack")
        raw, where = data["pack"], file.name
        pid = _need(raw, "id", str, where)
        own = [_template(t, pid, where) for t in _need(raw, "templates", list, where)]
        packs.append(Pack(pid, _need(raw, "name", str, where), raw.get("journalName") or raw["name"],
                          _need(raw, "summary", str, where), raw.get("order"), raw.get("defaultTemplate", ""),
                          own, list(raw.get("includes", [])), file.name))
    seen: Dict[str, str] = {}
    for pack in packs:
        for template in pack.own:
            if template.id in seen:
                raise LibraryError(f"{pack.source}: {template.id} is also in {seen[template.id]}")
            seen[template.id] = pack.source
    for pack in packs:
        for tid in pack.includes:
            if tid not in seen or seen[tid] == pack.source or pack.includes.count(tid) > 1:
                raise LibraryError(f"{pack.source}: includes {tid}, which is not another pack’s template, "
                                   "or is listed twice")
        listed = [t.id for t in pack.own] + pack.includes
        if pack.default_template and pack.default_template not in listed:
            raise LibraryError(f"{pack.source}: the default template {pack.default_template} is not in the pack")
    packs.sort(key=lambda p: (p.order is None, p.order or 0, p.name, p.source))
    return Library(packs)


# ----- words -----

def smart(text: str) -> str:
    """The app's straight quotes, curled as the site's copy has them."""
    text = re.sub(r'(^|[\s(\[{—–-])"', "\\1“", text)
    text = text.replace('"', "”")
    text = re.sub(r"(^|[\s(\[{—–-])'(?=\w)", "\\1‘", text)
    return text.replace("'", "’")


def duration_text(minutes: int) -> str:
    """As the app writes a Duration (DurationFormat): "5h 30m", "2h", "45m", "0m"."""
    hours, rest = divmod(int(minutes), 60)
    if hours and rest:
        return f"{hours}h {rest}m"
    return f"{hours}h" if hours else f"{rest}m"


def number_text(number) -> str:
    return str(int(number)) if float(number).is_integer() else f"{number:g}"


def _plural(day: int) -> str:
    return DAYS[day] + "s"


def reminder_text(reminder: Optional[dict]) -> str:
    if not reminder:
        return "None"
    days = sorted(set(reminder["weekdays"]))
    time = f"{reminder['hour']:02d}:{reminder['minute']:02d}"
    if days == [1, 2, 3, 4, 5, 6, 7]:
        when = "Every day"
    elif days == [2, 3, 4, 5, 6]:
        when = "Weekdays"
    elif days == [1, 7]:
        when = "Weekends"
    else:
        names = [_plural(d) for d in days]
        when = names[0] if len(names) == 1 else ", ".join(names[:-1]) + " and " + names[-1]
    return f"{when} at {time}"


def listing(words: List[str]) -> str:
    return words[0] if len(words) == 1 else ", ".join(words[:-1]) + " and " + words[-1]


def long_date(day: datetime.date) -> str:
    return f"{day.day} {MONTHS[day.month - 1]} {day.year}"


def short_date(day: datetime.date) -> str:
    return f"{day.day} {MONTHS[day.month - 1][:3]} {day.year}"


# ----- examples -----

@dataclass
class Example:
    when: datetime.datetime
    title: str
    values: dict
    source: str


def _check_value(f: Field, value, where: str) -> Optional[str]:
    """Why `value` can't be `f`'s sample value, or None when it can."""
    def strings(v, rule: str = "") -> bool:
        return isinstance(v, list) and bool(v) and all(isinstance(s, str) and s.strip() for s in v) and (
            not rule or all(re.fullmatch(rule, s) for s in v))
    kind = f.type
    is_number = isinstance(value, (int, float)) and not isinstance(value, bool)
    if kind in ("text", "richText"):
        ok = isinstance(value, str) and bool(value.strip())
    elif kind == "checklist":
        ok = strings(value, r"\[[ x]\] \S.*")
        if not ok:
            return f"{where}: a Checklist is a list of “[x] done” and “[ ] open” lines"
    elif kind == "number":
        ok = is_number
    elif kind == "duration":
        ok = isinstance(value, int) and not isinstance(value, bool) and value >= 0
        if not ok:
            return f"{where}: a Duration is a whole number of minutes"
    elif kind in ("rating", "mood"):
        ok = isinstance(value, int) and not isinstance(value, bool) and 1 <= value <= 5
        if not ok:
            return f"{where}: a {TYPE_NAMES[kind]} is a whole number from 1 to 5, not {value!r}"
    elif kind == "date":
        try:
            ok = bool(datetime.date.fromisoformat(value))
        except (TypeError, ValueError):
            ok = False
    elif kind == "timeRange":
        m = re.fullmatch(r"(\d\d):(\d\d)–(\d\d):(\d\d)", value) if isinstance(value, str) else None
        ok = bool(m) and int(m.group(1)) < 24 and int(m.group(3)) < 24 and int(m.group(2)) < 60 and \
            int(m.group(4)) < 60 and (m.group(1), m.group(2)) < (m.group(3), m.group(4))
        if not ok:
            return f"{where}: a Time range is “HH:MM–HH:MM”, with an en dash, ending after it starts"
    elif kind == "singleSelect":
        ok = value in [o.key for o in f.options]
        if not ok:
            return f"{where}: {value!r} is not one of the field’s options ({', '.join(o.key for o in f.options)})"
    elif kind == "multiSelect":
        keys = [o.key for o in f.options]
        ok = strings(value) and len(set(value)) == len(value) and all(v in keys for v in value)
        if not ok:
            return f"{where}: a Multi-select is a list of the field’s options ({', '.join(keys)})"
    elif kind == "tags":
        ok = strings(value, TAG.pattern) and len(set(value)) == len(value)
        if not ok:
            return f"{where}: tags are lowercase words joined by hyphens, as the app keeps them"
    elif kind in ("person", "project"):
        ok = strings(value) and len(set(value)) == len(value)
    elif kind == "link":
        url = value.get("url", "") if isinstance(value, dict) else ""
        host = re.match(r"https://([^/:?#]+)", url)
        ok = (isinstance(value, dict) and set(value) == {"title", "url"} and isinstance(value["title"], str)
              and bool(value["title"].strip()) and bool(host) and bool(EXAMPLE_HOSTS.fullmatch(host.group(1))))
        if not ok:
            return f"{where}: a Link is {{\"title\", \"url\"}} with an https URL on example.com, .net or .org"
    elif kind == "attachment":
        ok = isinstance(value, list) and bool(value) and all(
            isinstance(v, list) and len(v) == 2 and all(isinstance(s, str) and s.strip() for s in v) for v in value)
        if not ok:
            return f"{where}: an Attachment is a list of [file name, what it is] pairs"
    else:
        return f"{where}: a {TYPE_NAMES[kind]} field holds no value"
    return None if ok else f"{where}: {value!r} is not a sample a {TYPE_NAMES[kind]} field can hold"


def _copy(value) -> List[str]:
    """The strings in a sample value a reader sees (not a link's address)."""
    if isinstance(value, str):
        return [value]
    if isinstance(value, dict):
        return [value.get("title", "")]
    if isinstance(value, list):
        return [s for v in value for s in _copy(v)]
    return []


def load_examples(folder: Path, library: Library) -> Dict[str, Example]:
    build = _build()
    examples: Dict[str, Example] = {}
    problems: List[str] = []
    for file in sorted(folder.glob("*.json")) if folder.is_dir() else []:
        rel = f"{EXAMPLES}/{file.name}"
        try:
            data = json.loads(file.read_text(encoding="utf-8"))
        except json.JSONDecodeError as error:
            raise LibraryError(f"{rel}: not JSON ({error})") from None
        for tid, raw in data.items():
            where = f"{rel}: {tid}"
            template = library.templates.get(tid)
            if template is None:
                problems.append(f"{where}: no such template in the library")
                continue
            if file.stem != template.pack:
                problems.append(f"{where}: the example belongs in {EXAMPLES}/{template.pack}.json")
            try:
                when = datetime.datetime.strptime(raw.get("date", ""), "%Y-%m-%d %H:%M")
            except ValueError:
                problems.append(f"{where}: the date is “YYYY-MM-DD HH:MM”")
                continue
            values = raw.get("values", {})
            for key in sorted(set(raw) - {"date", "title", "values"}):
                problems.append(f"{where}: unknown key '{key}' (an example has date, title and values)")
            keys = {f.key for f in template.fields}
            for key in sorted(set(values) - keys):
                problems.append(f"{where}: {key}: the template has no such field")
            for f in template.fields:
                if f.type in NO_VALUE:
                    continue
                if f.key not in values:
                    problems.append(f"{where}: {f.key}: no sample value; every field gets one")
                    continue
                problem = _check_value(f, values[f.key], f"{where}: {f.key}")
                if problem:
                    problems.append(problem)
            for key, value in [("title", raw.get("title", ""))] + list(values.items()):
                for text in _copy(value):
                    problems += [p.replace(":1: ", ": ", 1) for p in build.lint_copy(text, f"{where}: {key}")]
            examples[tid] = Example(when, raw.get("title", ""), values, rel)
    for tid in sorted(set(library.templates) - set(examples)):
        problems.append(f"{EXAMPLES}/{library.templates[tid].pack}.json: {tid}: no example; "
                        "write one filled-in entry for it")
    if problems:
        raise LibraryError("\n".join(problems))
    return examples


# ----- the example entry, as the app draws it -----

def _esc(text: str) -> str:
    return _build().esc(text)


def _inline(text: str) -> str:
    return _archive().inline(text)


def _bars(value: int) -> str:
    return ('<span class="entry-bars" aria-hidden="true">'
            + "".join('<span class="on"></span>' if n < value else "<span></span>" for n in range(5)) + "</span>")


def pill(option: Option) -> str:
    """A select option, as the app's OptionPill: a status pill, or a neutral pill with its journal colour's dot."""
    kind = "tone" if option.color in STATUS_COLORS else "dot"
    return f'<span class="entry-pill entry-{kind}-{option.color}">{_esc(smart(option.label))}</span>'


def _chips(names: List[str], first: str = "") -> str:
    return "".join(f'<span class="entry-chip{first if n == 0 else ""}">{_esc(name)}</span>'
                   for n, name in enumerate(names))


def property_value(f: Field, value) -> str:
    kind = f.type
    if kind == "rating":
        return _bars(value) + RATING_WORDS[value - 1]
    if kind == "mood":
        return _bars(value) + MOOD_WORDS[value - 1]
    if kind == "duration":
        return f'<span class="entry-mono">{duration_text(value)}</span>'
    if kind == "number":
        return f'<span class="entry-mono">{number_text(value)}</span>'
    if kind == "date":
        return f'<span class="entry-mono">{short_date(datetime.date.fromisoformat(value))}</span>'
    if kind == "timeRange":
        return f'<span class="entry-mono">{_esc(value)}</span>'
    if kind == "singleSelect":
        return pill(next(o for o in f.options if o.key == value))
    if kind == "multiSelect":
        return "".join(pill(o) for o in f.options if o.key in value)
    if kind == "tags":
        return _chips(["#" + t for t in value], " entry-tag-accent")
    if kind == "person":
        return _chips(value)
    if kind == "project":
        return _chips(value, " entry-chip-project")
    if kind == "link":
        host = re.match(r"https://([^/:?#]+)", value["url"]).group(1)
        path = value["url"][len("https://" + host):].rstrip("/")
        return (f'<span class="entry-link">{_esc(value["title"])}</span>'
                f'<span class="entry-host">{_esc(host + path)}</span>')
    raise LibraryError(f"{f.key}: a {TYPE_NAMES[kind]} is not drawn in the grid")


def _paragraphs(text: str, rich: bool) -> str:
    parts = []
    for block in re.split(r"\n\s*\n", text.strip()):
        lines = block.splitlines()
        if rich and all(line.startswith("- ") for line in lines):
            parts.append("<ul>" + "".join(f"<li>{_inline(line[2:])}</li>" for line in lines) + "</ul>")
        else:
            words = [(_inline(line) if rich else _esc(line)) for line in lines]
            parts.append("<p>" + "<br>".join(words) + "</p>")
    return "".join(parts)


def page_value(f: Field, value) -> str:
    kind = f.type
    if kind in ("text", "richText"):
        return f'<div class="entry-prose">{_paragraphs(value, kind == "richText")}</div>'
    if kind == "checklist":
        items = []
        for line in value:
            done = line.startswith("[x]")
            state = '<span class="visually-hidden">Done: </span>' if done else ""
            mark = ' class="done"' if done else ""
            items.append(f'<li{mark}><span class="entry-box" aria-hidden="true">'
                         f"</span>{state}<span>{_inline(line[4:])}</span></li>")
        return '<ul class="entry-checklist">' + "".join(items) + "</ul>"
    if kind == "attachment":
        rows = []
        for name, detail in value:
            ext = name.rsplit(".", 1)[-1].upper()[:4] if "." in name else "FILE"
            rows.append(f'<div class="entry-file"><span class="entry-file-icon" aria-hidden="true">{_esc(ext)}</span>'
                        f'<span class="entry-file-name">{_esc(name)}</span>'
                        f'<span class="entry-file-detail">{_esc(detail)}</span></div>')
        return "".join(rows)
    raise LibraryError(f"{f.key}: a {TYPE_NAMES[kind]} is not drawn on the page")


def render_entry(template: Template, example: Example) -> str:
    when = example.when
    week = when.isocalendar()[1]
    head = [f'  <p class="entry-day">{DAYS[when.isoweekday() % 7 + 1].upper()} · WEEK {week}</p>',
            f'  <p class="entry-date">{long_date(when.date())}</p>']
    if example.title:
        head.append(f'  <p class="entry-title">{_esc(example.title)}</p>')
    head.append(f'  <p class="entry-meta"><span class="entry-template">{_esc(template.name)}</span>'
                f'<span class="entry-time">{when:%H:%M}</span></p>')
    grid, page = [], []
    for f in template.fields:
        if f.type in PAGE_FIELDS:
            if f.type == "heading":
                page.append(f'    <p class="entry-heading">{_esc(smart(f.label))}</p>')
            elif f.type == "divider":
                page.append('    <hr class="entry-rule">')
            else:
                body = page_value(f, example.values[f.key])
                if f.warning:
                    body = f'<div class="entry-well">{body}</div>'
                page.append(f'    <div class="entry-field"><p class="entry-label">{_esc(smart(f.label))}</p>{body}</div>')
        else:
            grid.append(f'    <div><dt>{_esc(smart(f.label))}</dt><dd>{property_value(f, example.values[f.key])}</dd></div>')
    parts = head
    if grid:
        parts.append('  <dl class="entry-props">\n' + "\n".join(grid) + "\n  </dl>")
    if page:
        parts.append('  <div class="entry-long">\n' + "\n".join(page) + "\n  </div>")
    return (f'<article class="entry" aria-label="An example {_esc(template.name)} entry">\n'
            + "\n".join(parts) + "\n</article>")


# ----- pages -----

def page_path(template: Template) -> str:
    return f"{OUT}/{template.pack}/{template.slug}/index.html"


def pack_path(pack: Pack) -> str:
    return f"{OUT}/{pack.id}/index.html"


def _dir(path: str) -> str:
    return posixpath.dirname(path) + "/"


def describe(where: str, *candidates: str) -> str:
    """The first candidate that fits a search result (50–160 characters)."""
    build = _build()
    for text in candidates:
        if build.DESCRIPTION_MIN <= len(text) <= build.DESCRIPTION_MAX:
            return text
    raise LibraryError(f"{where}: no description fits {build.DESCRIPTION_MIN}–{build.DESCRIPTION_MAX} characters")


def _crumb_kicker(page: str, crumbs: List[Tuple[str, str]]) -> str:
    build = _build()
    trail = '<span class="crumbs-sep" aria-hidden="true">/</span>'.join(
        f'<a href="{build.href(page, path)}">{_esc(name)}</a>' for name, path in crumbs)
    return (f'<nav class="kicker crumbs" aria-label="Breadcrumb"><span class="crumbs-mark" aria-hidden="true">'
            f"{KANJI}</span>{trail}</nav>")


def _item_list(items: List[Tuple[str, str]]) -> dict:
    build = _build()
    return {"@context": "https://schema.org", "@type": "ItemList", "itemListElement": [
        {"@type": "ListItem", "position": n, "url": build.url_for(path), "name": name}
        for n, (name, path) in enumerate(items, 1)]}


def _base_crumbs() -> List[Tuple[str, str]]:
    return [("Dayfolio", "apps/dayfolio/"), ("Templates", f"{OUT}/")]


def _generator(*sources: str) -> str:
    return f"{GENERATED} from {' and '.join(sources)}: run the tool, never edit this page."


def _titles(library: Library) -> Dict[str, str]:
    """Each template's page title: "<name> template", with the pack's name when two templates share a name."""
    names: Dict[str, int] = {}
    for t in library.templates.values():
        names[t.name.lower()] = names.get(t.name.lower(), 0) + 1
    return {t.id: f"{t.name} template" + (f" for {library.owner(t).name}" if names[t.name.lower()] > 1 else "")
            for t in library.templates.values()}


def _field_item(f: Field) -> str:
    parts = [f'<p class="tpl-field-head"><span class="tpl-field-name">{_esc(smart(f.label))}</span>'
             f'<span class="tpl-type">{TYPE_NAMES[f.type]}</span></p>']
    if f.prompt:
        parts.append(f'<p class="tpl-prompt">{_esc(smart(f.prompt))}</p>')
    if f.options:
        parts.append('<p class="tpl-options">' + "".join(pill(o) for o in f.options) + "</p>")
    if f.carry_over:
        what = ("the items you haven’t ticked in your previous entry with this template" if f.type == "checklist"
                else "the value from your previous entry with this template")
        parts.append(f'<p class="tpl-note">Carries over: a new entry starts with {what}.</p>')
    if f.warning:
        parts.append('<p class="tpl-note">Drawn in an amber well, so it stands out on the page.</p>')
    return "<li>" + "".join(parts) + "</li>"


