def build(root: Path) -> Dict[str, str]:
    """Every page the generator owns, from the site root, with the content it should have."""
    folder = root / GALLERY_MARKDOWN
    if folder.is_dir() and any(folder.glob("*.md")):
        raise LibraryError(f"{GALLERY_MARKDOWN}/ holds Markdown, but this generator writes the gallery; "
                           "remove it (tools/dayfolio-build.py would make the same pages)")
    library = load_library(root / LIBRARY)
    examples = load_examples(root / EXAMPLES, library)
    titles = _titles(library)
    pages = {GALLERY: gallery_page(root, library)}
    for pack in library.packs:
        pages[pack_path(pack)] = pack_page(root, library, pack)
    for template in library.templates.values():
        pages[page_path(template)] = template_page(root, library, template, examples[template.id],
                                                   titles[template.id])
    return pages


# ----- write and check -----

def owned(root: Path) -> List[str]:
    folder = root / OUT
    return sorted(p.relative_to(root).as_posix() for p in folder.rglob("*.html")
                  if f"<!-- {GENERATED} from " in p.read_text(encoding="utf-8")) if folder.is_dir() else []


def app_library(path) -> Path:
    path = Path(path).expanduser()
    if (path / APP_LIBRARY).is_dir():
        return path / APP_LIBRARY
    if path.is_dir() and any(path.glob("*.json")):
        return path
    raise LibraryError(f"{path}: neither the Dayfolio repository nor its {APP_LIBRARY} folder")


def compare(root: Path, app) -> List[str]:
    source, copy = app_library(app), root / LIBRARY
    names = sorted({f.name for f in source.glob("*.json")} | ({f.name for f in copy.glob("*.json")}
                                                               if copy.is_dir() else set()))
    problems = []
    for name in names:
        theirs, ours = source / name, copy / name
        if not ours.is_file() or not theirs.is_file() or ours.read_bytes() != theirs.read_bytes():
            problems.append(f"{LIBRARY}/{name} is not the app’s; run python3 tools/dayfolio-templates.py "
                            f"--library {app}")
    return problems


def sync(root: Path, app) -> List[str]:
    """Copy the app's packs into the site, after checking them; a pack the app dropped goes too."""
    source = app_library(app)
    load_library(source)
    copy = root / LIBRARY
    copy.mkdir(parents=True, exist_ok=True)
    changed = []
    names = {f.name for f in source.glob("*.json")}
    for file in sorted(source.glob("*.json")):
        target = copy / file.name
        if not target.is_file() or target.read_bytes() != file.read_bytes():
            target.write_bytes(file.read_bytes())
            changed.append(f"{LIBRARY}/{file.name}")
    for file in sorted(copy.glob("*.json")):
        if file.name not in names:
            file.unlink()
            changed.append(f"{LIBRARY}/{file.name} (removed)")
    return changed


def check(root: Path, app=None) -> List[str]:
    problems = compare(root, app) if app else []
    if not (root / LIBRARY).is_dir() and not owned(root):
        return problems  # a site without the gallery (the build's own test fixture)
    try:
        expected = build(root)
    except LibraryError as error:
        return problems + [f"the generator stops: {error}"]
    for rel, text in sorted(expected.items()):
        file = root / rel
        if not file.is_file():
            problems.append(f"{rel} is missing; run python3 tools/dayfolio-templates.py")
        elif file.read_text(encoding="utf-8") != text:
            problems.append(f"{rel} differs from what the library makes; run python3 tools/dayfolio-templates.py")
    for rel in owned(root):
        if rel not in expected:
            problems.append(f"{rel} is for a template or pack the library no longer has; "
                            "run python3 tools/dayfolio-templates.py")
    return problems


def write(root: Path) -> List[str]:
    expected = build(root)
    changed = []
    for rel, text in sorted(expected.items()):
        file = root / rel
        if not file.is_file() or file.read_text(encoding="utf-8") != text:
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_text(text, encoding="utf-8")
            changed.append(rel)
    for rel in owned(root):
        if rel not in expected:
            file = root / rel
            file.unlink()
            folder = file.parent
            while folder != root / OUT and not any(folder.iterdir()):
                folder.rmdir()
                folder = folder.parent
            changed.append(f"{rel} (removed)")
    return changed


def main(argv: Optional[List[str]] = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    checking = "--check" in args
    if checking:
        args.remove("--check")
    app = None
    if "--library" in args:
        at = args.index("--library")
        if at + 1 >= len(args):
            print(__doc__)
            return 2
        app = args[at + 1]
        del args[at:at + 2]
    if args:
        print(__doc__)
        return 2
    if checking:
        try:
            problems = check(ROOT, app)
        except LibraryError as error:
            problems = [str(error)]
        for problem in problems:
            print(f"  · {problem}")
        print("FAIL — the template pages differ from the library." if problems
              else "OK — every template page matches the library.")
        return 1 if problems else 0
    try:
        copied = sync(ROOT, app) if app else []
        changed = write(ROOT)
        library = load_library(ROOT / LIBRARY)
    except LibraryError as error:
        print(f"FAIL — {error}")
        return 1
    for rel in copied:
        print(f"copied {rel}")
    for rel in changed:
        print(f"wrote {rel}")
    print(f"OK — {len(library.templates)} templates in {len(library.packs)} packs; "
          f"{len(copied) + len(changed)} file(s) changed.")
    if changed:
        print("Next: python3 tools/dayfolio-build.py (sitemap.xml), then python3 tools/check-site.py.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
