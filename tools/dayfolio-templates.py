#!/usr/bin/env python3
"""Generate Dayfolio's template gallery from the app's template library.

    python3 tools/dayfolio-templates.py                                  # write the gallery
    python3 tools/dayfolio-templates.py --library /path/to/dayfolio      # copy the app's packs in, then write
    python3 tools/dayfolio-templates.py --check                          # write nothing; fail on a difference
    python3 tools/dayfolio-templates.py --check --library /path/to/dayfolio
                                                                         # also fail if the copy is behind the app

The app bundles its templates as JSON, one file per pack, in the Dayfolio repository's
Packages/DayfolioKit/Sources/DayfolioDomain/Resources/Library/ (the format is
Library/PackFormat.md beside it). --library copies those files into content/dayfolio/library/,
so the site can be checked and rebuilt without the app's repository. From that copy and the
sample values in content/dayfolio/examples/<pack-id>.json (written for the website: one
filled-in entry per template), this writes, through tools/dayfolio-build.py's shell:

    apps/dayfolio/templates/                         the gallery, every pack in the app's order
    apps/dayfolio/templates/<pack-id>/               a page per pack
    apps/dayfolio/templates/<pack-id>/<template>/    a page per template, under the pack that owns it

A template page says what the template is for, its cadence and suggested reminder, every field
with its type, options and prompt, the packs that list it, and an example entry drawn the way the
app draws one. The generator stops, naming the file, at a pack the app would refuse, a template
without an example, a field without a sample value, a value its field could not hold, or sample
copy against the site's rules. A page whose template left the library is removed. GitHub Pages
serves files, so the pages are committed, and tools/check-site.py runs --check. After a write, run
tools/dayfolio-build.py, which lists the pages in sitemap.xml. Standard library only.
"""

