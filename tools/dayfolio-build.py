def href(page: str, target: str) -> str:
    """A relative link from `page` (a file, from the site root) to `target` (a file, or a folder ending
    in /, from the site root; "" or "/" is the root), keeping any #fragment."""
    target, _, fragment = target.partition("#")
    here = posixpath.dirname(page) or "."
    folder = target in ("", "/") or target.endswith("/")
    rel = posixpath.relpath(target.strip("/") or ".", here)
    if folder:
        rel = "./" if rel == "." else rel + "/"
    return rel + (f"#{fragment}" if fragment else "")


def rebase(fragment: str, source_dir: str, page: str) -> str:
    """Rewrite the relative href and src attributes of `fragment`, written for a page in `source_dir`,
    so they work from `page`."""
    def fix(m: re.Match) -> str:
        attr, url = m.group(1), m.group(2)
        if re.match(r"[a-zA-Z][a-zA-Z0-9+.-]*:|/|#", url):
            return m.group(0)
        path, _, fragment_id = url.partition("#")
        folder = path in ("", ".", "./") or path.endswith("/")
        target = posixpath.normpath(posixpath.join(source_dir, path or "."))
        target = "" if target == "." else target + ("/" if folder else "")
        return f'{attr}="{href(page, target + (f"#{fragment_id}" if fragment_id else ""))}"'
    return re.sub(r'\b(href|src)="([^"]*)"', fix, fragment)


