# ----- pictures -----

def has_alpha(path: Path) -> bool:
    """Whether a WebP picture keeps an alpha channel: a window capture's transparent corners."""
    data = path.read_bytes()
    if data[:4] != b"RIFF" or data[8:12] != b"WEBP":
        return False
    if data[12:16] == b"VP8X":
        return bool(data[20] & 0x10)
    if data[12:16] == b"VP8L" and data[20] == 0x2F:
        return bool(int.from_bytes(data[21:25], "little") >> 28 & 1)
    return False


def image_size(path: Path) -> Tuple[int, int]:
    """Width and height of a PNG, JPEG or WebP file, from its header."""
    data = path.read_bytes()
    if data[:8] == b"\x89PNG\r\n\x1a\n" and data[12:16] == b"IHDR":
        return struct.unpack(">II", data[16:24])
    if data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        chunk = data[12:16]
        if chunk == b"VP8X":
            return 1 + int.from_bytes(data[24:27], "little"), 1 + int.from_bytes(data[27:30], "little")
        if chunk == b"VP8 " and data[23:26] == b"\x9d\x01\x2a":
            return (int.from_bytes(data[26:28], "little") & 0x3FFF, int.from_bytes(data[28:30], "little") & 0x3FFF)
        if chunk == b"VP8L" and data[20] == 0x2F:
            bits = int.from_bytes(data[21:25], "little")
            return (bits & 0x3FFF) + 1, ((bits >> 14) & 0x3FFF) + 1
    if data[:2] == b"\xff\xd8":
        i = 2
        while i + 9 < len(data):
            if data[i] != 0xFF:
                i += 1
                continue
            marker, length = data[i + 1], struct.unpack(">H", data[i + 2:i + 4])[0]
            if 0xC0 <= marker <= 0xCF and marker not in (0xC4, 0xC8, 0xCC):
                height, width = struct.unpack(">HH", data[i + 5:i + 9])
                return width, height
            i += 2 + length
    raise BuildError(f"{path}: not a PNG, JPEG or WebP picture this build can read")


def resolve(root: Path, page: str, src: str, source: str) -> Tuple[str, Path]:
    if re.match(r"[a-zA-Z][a-zA-Z0-9+.-]*:|/", src):
        raise BuildError(f"{source}: {src}: a picture lives on this site, next to the page, by a relative path")
    site_path = posixpath.normpath(posixpath.join(posixpath.dirname(page), src))
    file = root / site_path
    if not file.is_file():
        raise BuildError(f"{source}: the picture {src} is not at {site_path}")
    return site_path, file


# ----- copy rules -----

EMOJI = re.compile("[\U0001F000-\U0001FAFF☀-➿️]")


def lint_copy(text: str, source: str, first_line: int = 1) -> List[str]:
    """The site's copy rules, for what a reader sees: curly quotes and apostrophes, no exclamation
    marks, no emoji. Code, link targets and picture files are left alone."""
    problems, fenced = [], False
    for number, line in enumerate(text.splitlines(), first_line):
        if line.startswith("```"):
            fenced = not fenced
            continue
        if fenced:
            continue
        plain = re.sub(r"`[^`]*`", "", line)
        plain = PICTURE.sub(lambda m: f"{m.group(1)} {m.group(3) or ''}", plain)
        plain = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", plain)
        plain = re.sub(r"<https?://[^>]*>", "", plain)
        for pattern, rule in ((r"[\"']", "a straight quote: use ‘ ’ “ ” and ’ for an apostrophe"),
                              (r"!", "an exclamation mark: the site's copy has none"),
                              (EMOJI, "an emoji: the site's copy has none")):
            if re.search(pattern, plain):
                problems.append(f"{source}:{number}: {rule}: {line.strip()[:80]}")
    return problems


# ----- sources -----

def parse_page(text: str, source: str) -> Tuple[Dict[str, str], str, int]:
    """Front matter and body. Returns the fields, the body and the file line the body starts on."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        raise BuildError(f"{source}:1: no front matter: start with a --- line, the fields, then another ---")
    fields: Dict[str, str] = {}
    for number, line in enumerate(lines[1:], 2):
        if line.strip() == "---":
            return fields, "\n".join(lines[number:]) + "\n", number + 1
        m = re.fullmatch(r"([a-z_]+):\s*(.*?)\s*", line)
        if not m:
            raise BuildError(f"{source}:{number}: not a field (name: value): {line.strip()}")
        if m.group(1) in fields:
            raise BuildError(f"{source}:{number}: {m.group(1)} is given twice")
        fields[m.group(1)] = m.group(2)
    raise BuildError(f"{source}: the front matter has no closing --- line")


def check_fields(fields: Dict[str, str], kind: str, source: str) -> None:
    required, optional = FIELDS[kind]
    for name in sorted(set(fields) - required - optional):
        raise BuildError(f"{source}: unknown field '{name}' (a {kind} page takes {', '.join(sorted(required | optional))})")
    for name in sorted(required - set(fields)):
        raise BuildError(f"{source}: the field '{name}' is missing")
    for name, value in fields.items():
        if not value:
            raise BuildError(f"{source}: the field '{name}' is empty")
    if len(fields["title"]) > TITLE_MAX:
        raise BuildError(f"{source}: the title is {len(fields['title'])} characters; keep it to {TITLE_MAX}")
    if not DESCRIPTION_MIN <= len(fields["description"]) <= DESCRIPTION_MAX:
        raise BuildError(f"{source}: the description is {len(fields['description'])} characters; "
                         f"search results show {DESCRIPTION_MIN} to {DESCRIPTION_MAX}")
    if "slug" in fields and not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", fields["slug"]):
        raise BuildError(f"{source}: the slug '{fields['slug']}' is not lowercase words joined by hyphens")
    for name in ("date", "updated"):
        if name in fields:
            try:
                datetime.date.fromisoformat(fields[name])
            except ValueError:
                raise BuildError(f"{source}: the {name} '{fields[name]}' is not a real YYYY-MM-DD day") from None
    if "order" in fields and not re.fullmatch(r"[1-9][0-9]*", fields["order"]):
        raise BuildError(f"{source}: the order '{fields['order']}' is not a whole number from 1")
    if ("image" in fields) != ("image_alt" in fields):
        raise BuildError(f"{source}: image and image_alt go together")


def _load(name: str, file: str):
    """Another tool in this folder, as a module (once: dataclasses need it in sys.modules)."""
    if name not in sys.modules:
        spec = importlib.util.spec_from_file_location(name, Path(__file__).with_name(file))
        module = importlib.util.module_from_spec(spec)
        sys.modules[name] = module
        spec.loader.exec_module(module)
    return sys.modules[name]


def _archive():
    return _load("archive_page", "archive-page.py")


def markdown(root: Path, md: str, page: str, source: str) -> str:
    fenced = False
    for line in md.splitlines():
        fenced = fenced != line.startswith("```")
        if not fenced and re.match(r"# ", line):
            raise BuildError(f"{source}: a # heading is a second h1; the title comes from the front matter, "
                             "so start the body's headings at ##")

    app = app_for(page)

    def link(label: str, url: str) -> str:
        return f'<a href="{url}">{label}</a>'

    def picture_file(src: str, what: str) -> Tuple[Path, Tuple[int, int]]:
        """A WebP picture next to the page, small enough, and its size."""
        _, file = resolve(root, page, src, source)
        if file.suffix.lower() != ".webp":
            raise BuildError(f"{source}: the {what} {src} is not webp; pictures in pages are WebP")
        if file.stat().st_size > PICTURE_MAX_BYTES:
            raise BuildError(f"{source}: the {what} {src} is {file.stat().st_size // 1000} KB; "
                             f"keep pictures under {PICTURE_MAX_BYTES // 1000} KB")
        return file, image_size(file)

    def classes(kind: str, width: int, height: int, window: bool) -> str:
        shape = "portrait" if height > width else "landscape"
        names = ["figure", *([kind] if kind else []), f"figure-{shape}"]
        if app.window_figures and shape == "landscape":
            names.append("figure-wide")      # a Mac window, drawn wider than the column of text
            if window:
                names.append("figure-window")  # transparent rounded corners: a shadow, not a frame
        return " ".join(names)

    def clip(alt: str, src: str, caption: str, archive) -> str:
        """A short film: a <video> a visitor starts, muted and inline, over a poster frame beside it
        (clip.mp4 and clip-poster.webp), playable while it downloads."""
        if not alt.strip():
            raise BuildError(f"{source}: the clip {src} has no alt text; say what it shows")
        site_path = posixpath.normpath(posixpath.join(posixpath.dirname(page), src))
        if re.match(r"[a-zA-Z][a-zA-Z0-9+.-]*:|/", src) or not (root / site_path).is_file():
            raise BuildError(f"{source}: the clip {src} is not at {site_path}, next to the page")
        file = root / site_path
        if file.stat().st_size > CLIP_MAX_BYTES:
            raise BuildError(f"{source}: the clip {src} is {file.stat().st_size // 1_000_000} MB; "
                             f"keep clips under {CLIP_MAX_BYTES // 1_000_000} MB")
        boxes = _check_site_module().mp4_boxes(file)
        if not boxes or boxes[0] != b"ftyp":
            raise BuildError(f"{source}: the clip {src} is not an MP4 file")
        if b"moov" not in boxes or (b"mdat" in boxes and boxes.index(b"moov") > boxes.index(b"mdat")):
            raise BuildError(f"{source}: the clip {src} keeps its moov box after the media, so it cannot play "
                             "until it has all downloaded; remux it with ffmpeg -movflags +faststart")
        poster = src[:-len(".mp4")] + "-poster.webp"
        if not (root / posixpath.normpath(posixpath.join(posixpath.dirname(page), poster))).is_file():
            raise BuildError(f"{source}: the clip {src} has no poster frame: put {poster} next to it")
        _, (width, height) = picture_file(poster, "poster frame")
        caption_html = f"<figcaption>{archive.inline(caption)}</figcaption>" if caption else ""
        return (f'<figure class="{classes("figure-clip", width, height, False)}"><video controls muted playsinline '
                f'preload="none" poster="{esc(poster)}" width="{width}" height="{height}" '
                f'aria-label="{esc(alt.strip())}"><source src="{esc(src)}" type="video/mp4">'
                f'<p>Your browser can’t play this clip here. <a href="{esc(src)}">Open it on its own</a> (MP4).</p>'
                f'</video>{caption_html}</figure>')

    def figure(alt: str, src: str, caption: str, archive) -> str:
        if src.lower().endswith(".mp4"):
            return clip(alt, src, caption, archive)
        if not alt.strip():
            raise BuildError(f"{source}: the picture {src} has no alt text; say what it shows")
        file, (width, height) = picture_file(src, "picture")
        window = app.window_figures and has_alpha(file)
        caption_html = f"<figcaption>{archive.inline(caption)}</figcaption>" if caption else ""
        return (f'<figure class="{classes("", width, height, window)}"><img src="{esc(src)}" '
                f'alt="{esc(alt.strip())}" width="{width}" height="{height}" loading="lazy">{caption_html}</figure>')

    archive = _archive()
    return archive.convert(md, link=link, figure=lambda a, s, c: figure(a, s, c, archive))


@dataclass
class Source:
    section: str
    kind: str
    fields: Dict[str, str]
    body: str
    body_line: int
    path: str          # the source file, from the site root
    out: str           # the page it makes, from the site root


def read_sources(root: Path, app: App = DAYFOLIO) -> Tuple[Dict[str, Source], Dict[str, List[Source]]]:
    """Each of the app's sections' own page (index.md) and its pages, checked and ordered as the section lists
    them."""
    indexes: Dict[str, Source] = {}
    pages: Dict[str, List[Source]] = {}
    for key, section in app.sections.items():
        folder = root / app.content / key
        pages[key] = []
        for file in sorted(folder.glob("*.md")) if folder.is_dir() else []:
            rel = file.relative_to(root).as_posix()
            text = file.read_text(encoding="utf-8")
            fields, body, body_line = parse_page(text, rel)
            kind = "section" if file.name == "index.md" else section.kind
            check_fields(fields, kind, rel)
            problems = lint_copy("\n".join(text.splitlines()[1:body_line - 2]), rel, 2) + lint_copy(body, rel, body_line)
            if problems:
                raise BuildError("\n".join(problems))
            if kind == "section":
                indexes[key] = Source(key, kind, fields, body, body_line, rel, f"{app.dir}/{key}/index.html")
            else:
                out = f"{app.dir}/{key}/{fields['slug']}/index.html"
                pages[key].append(Source(key, kind, fields, body, body_line, rel, out))
        seen: Dict[str, str] = {}
        for item in pages[key]:
            for name in ("slug", "order"):
                value = item.fields.get(name)
                if value is not None and (name, value) in seen:
                    raise BuildError(f"{item.path}: the {name} '{value}' is already used by {seen[(name, value)]}")
                if value is not None:
                    seen[(name, value)] = item.path
        if section.kind == "topic":
            pages[key].sort(key=lambda s: int(s.fields["order"]))
        else:
            pages[key].sort(key=lambda s: (s.fields["date"], s.fields["title"]), reverse=True)
    return indexes, pages


# ----- the shell -----

def render_subnav(page: str) -> str:
    app = app_for(page)
    links = [f'  <a class="subnav-app" href="{href(page, app.dir + "/")}">{app.name}</a>']
    for label, target in app.subnav:
        site_target = f"{app.dir}/{target}"
        current = ""
        if page == site_target or (site_target.endswith("/") and page == site_target + "index.html"):
            current = ' aria-current="page"'
        elif target.endswith("/") and page.startswith(site_target):
            current = ' aria-current="true"'
        links.append(f'  <a href="{href(page, site_target)}"{current}>{label}</a>')
    return f'<nav class="subnav" aria-label="{app.name}">\n' + "\n".join(links) + "\n</nav>"


def with_subnav(text: str, page: str) -> str:
    nav = render_subnav(page)
    if SUBNAV_BLOCK.search(text):
        return SUBNAV_BLOCK.sub(lambda _: nav, text, count=1)
    if "</header>" in text:
        return text.replace("</header>", "</header>\n\n" + nav, 1)
    return text


def stylesheet_link(page: str) -> str:
    return f'<link rel="stylesheet" href="{href(page, "style.css")}?v={STYLE_VERSION}">'


def with_stylesheet(text: str, page: str) -> str:
    """The page's link to the site's stylesheet, asking for STYLE_VERSION; a page without one is left as it is."""
    return STYLESHEET_LINK.sub(lambda _: stylesheet_link(page), text, count=1)


def chrome(root: Path, page: str) -> Tuple[str, str]:
    """The site header and footer, as the page's app's product page has them, rebased to `page`."""
    app_dir = app_for(page).dir
    product = root / app_dir / "index.html"
    if not product.is_file():
        raise BuildError(f"{app_dir}/index.html is missing; the shell takes the site's header and footer from it")
    text = product.read_text(encoding="utf-8")
    parts = []
    for tag in ("header", "footer"):
        found = re.search(rf"<{tag}>.*?</{tag}>", text, re.S)
        if not found:
            raise BuildError(f"{app_dir}/index.html has no <{tag}>; the shell takes the site's from it")
        parts.append(rebase(found.group(0), app_dir, page))
    return parts[0], parts[1]


def breadcrumbs(crumbs: List[Tuple[str, str]]) -> dict:
    return {"@context": "https://schema.org", "@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": n, "name": name, "item": url_for(path)}
        for n, (name, path) in enumerate(crumbs, 1)]}


def render_page(root: Path, page: Page) -> str:
    app = app_for(page.path)
    url, full = url_for(page.path), page.title + app.suffix
    image, image_alt = page.image or app.card, page.image_alt or app.card_alt
    image_file = root / image
    if not image_file.is_file():
        raise BuildError(f"{page.path}: its social card {image} is missing")
    width, height = image_size(image_file)
    image_url = url_for(image)
    blocks = ([breadcrumbs(page.crumbs)] if page.crumbs else []) + page.jsonld
    head = [
        '<meta charset="UTF-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1.0">',
        *([app.banner] if app.banner else []),
        f"<title>{esc(full)}</title>",
        f'<meta name="description" content="{esc(page.description)}">',
        f'<link rel="canonical" href="{url}">',
        '<meta property="og:site_name" content="NinjaApps">',
        f'<meta property="og:type" content="{page.og_type}">',
        f'<meta property="og:title" content="{esc(full)}">',
        f'<meta property="og:description" content="{esc(page.description)}">',
        f'<meta property="og:url" content="{url}">',
        f'<meta property="og:image" content="{image_url}">',
        f'<meta property="og:image:width" content="{width}">',
        f'<meta property="og:image:height" content="{height}">',
        f'<meta property="og:image:alt" content="{esc(image_alt)}">',
        '<meta name="twitter:card" content="summary_large_image">',
        f'<meta name="twitter:title" content="{esc(full)}">',
        f'<meta name="twitter:description" content="{esc(page.description)}">',
        f'<meta name="twitter:image" content="{image_url}">',
        f'<meta name="twitter:image:alt" content="{esc(image_alt)}">',
        *page.head_extra,
        ICON_LINK,
        THEME,
        stylesheet_link(page.path),
        f'<script src="{href(page.path, "assets/theme.js")}" defer></script>',
        *(ld(block) for block in blocks),
    ]
    header, footer = chrome(root, page.path)
    note = f"<!-- {page.generator} -->\n" if page.generator else ""
    meta_line = f"\n  {page.meta_line}" if page.meta_line else ""
    after = f"\n{page.after}" if page.after else ""
    back = f'\n  <a class="backlink" href="{page.backlink[0]}">{page.backlink[1]}</a>' if page.backlink else ""
    return f"""<!DOCTYPE html>
<html lang="en" data-theme="light">
<head>
{chr(10).join(head)}
</head>
<body>
{note}
{header}

{render_subnav(page.path)}

<main>

<section class="page">
  {page.kicker}
  <h1 class="page-title">{esc(page.heading or page.title)}</h1>{meta_line}
  <div class="prose">

{page.body}

  </div>{after}{back}
</section>

</main>

{footer}

</body>
</html>
"""


# ----- the pages -----

def _social(root: Path, item: Source) -> Dict[str, str]:
    if "image" not in item.fields:
        return {}
    site_path, file = resolve(root, item.out, item.fields["image"], item.path)
    if file.suffix.lower() not in (".png", ".jpg", ".jpeg", ".webp"):
        raise BuildError(f"{item.path}: the social image {item.fields['image']} is not PNG, JPEG or WebP")
    image_size(file)
    return {"image": site_path, "image_alt": item.fields["image_alt"]}


def _app_box(page: str) -> str:
    app = app_for(page)
    store = (f'<a class="ticket" href="{app.store_url}"><span>Get it on the App Store</span></a>' if app.store_url
             else '<span class="ticket-soon">Coming to the Mac App Store</span>')
    return f"""  <aside class="appbox" aria-label="Get {app.name}">
    <img class="app-icon-sm" src="{href(page, app.icon)}" alt="{app.name} app icon" width="64" height="64" loading="lazy">
    <div>
      <p>{app.box}</p>
      <div class="actions">{store}<a class="btn" href="{href(page, app.dir + '/')}">About {app.name}</a></div>
    </div>
  </aside>"""


def _pager(item: Source, siblings: List[Source]) -> str:
    at = siblings.index(item)
    links = []
    if at > 0:
        prev = siblings[at - 1]
        links.append(f'    <a class="pager-prev" href="{href(item.out, posixpath.dirname(prev.out) + "/")}">'
                     f'<span class="pager-label">PREVIOUS</span>{esc(prev.fields["title"])}</a>')
    if at < len(siblings) - 1:
        nxt = siblings[at + 1]
        links.append(f'    <a class="pager-next" href="{href(item.out, posixpath.dirname(nxt.out) + "/")}">'
                     f'<span class="pager-label">NEXT</span>{esc(nxt.fields["title"])}</a>')
    if not links:
        return ""
    return '  <nav class="pager" aria-label="More of the guide">\n' + "\n".join(links) + "\n  </nav>"


def _listing(key: str, index_out: str, items: List[Source]) -> str:
    section = app_for(index_out).sections[key]
    if not items:
        return f'  <p class="listing-empty">{esc(section.empty)}</p>'
    cards = []
    for item in items:
        tag = f"{int(item.fields['order']):02d}" if section.kind == "topic" else item.fields["date"]
        cards.append(f"""    <a class="card" href="{href(index_out, posixpath.dirname(item.out) + '/')}">
      <span class="tag">{esc(tag)}</span>
      <h2>{esc(item.fields['title'])}</h2>
      <p>{esc(item.fields['description'])}</p>
    </a>""")
    return '  <div class="listing grid grid-2">\n' + "\n".join(cards) + "\n  </div>"


def _generator(item: Source) -> str:
    return f"{GENERATED} from {item.path}: edit that file and run the build, not this page."


def section_page(root: Path, key: str, index: Source, items: List[Source]) -> str:
    out = index.out
    app = app_for(out)
    section = app.sections[key]
    blocks = []
    if items:
        blocks.append({"@context": "https://schema.org", "@type": "ItemList", "itemListElement": [
            {"@type": "ListItem", "position": n, "url": url_for(posixpath.dirname(item.out) + "/"),
             "name": item.fields["title"]} for n, item in enumerate(items, 1)]})
    page = Page(
        path=out, title=index.fields["title"], description=index.fields["description"],
        heading=index.fields.get("heading", ""),
        kicker="",
        body=markdown(root, index.body, out, index.path),
        crumbs=[(app.name, f"{app.dir}/"), (section.name, f"{app.dir}/{key}/")],
        jsonld=blocks, after=_listing(key, out, items),
        backlink=(href(out, app.dir + "/"), f"Back to {app.name}"), generator=_generator(index),
        **_social(root, index))
    return render_page(root, page)


def content_page(root: Path, key: str, item: Source, siblings: List[Source]) -> str:
    fields, out = item.fields, item.out
    app = app_for(out)
    section = app.sections[key]
    url = url_for(out)
    social = _social(root, item)
    article = {
        "@context": "https://schema.org", "@type": "Article", "headline": fields["title"],
        "description": fields["description"], "datePublished": fields["date"],
        "dateModified": fields.get("updated", fields["date"]), "inLanguage": "en",
        "image": [url_for(social.get("image", app.card))], "mainEntityOfPage": url,
        "author": ORG, "publisher": PUBLISHER,
        "about": {"@type": "SoftwareApplication", "name": app.name, "url": url_for(f"{app.dir}/")},
    }
    crumbs = [(app.name, f"{app.dir}/"), (section.name, f"{app.dir}/{key}/"), (fields["title"], out)]
    trail = '<span class="crumbs-sep" aria-hidden="true">/</span>'.join(
        f'<a href="{href(out, path)}">{esc(name)}</a>' for name, path in crumbs[:-1])
    kicker = f'<nav class="crumbs" aria-label="Breadcrumb">{trail}</nav>'
    meta_line, head_extra = "", []
    if section.kind == "article":
        dates = f"PUBLISHED {fields['date']}" + (f" · UPDATED {fields['updated']}" if "updated" in fields else "")
        meta_line = f'<p class="effective">{dates}</p>'
        head_extra = [f'<meta property="article:published_time" content="{fields["date"]}">']
    after = [part for part in (_pager(item, siblings) if section.pager else "", _app_box(out)) if part]
    page = Page(
        path=out, title=fields["title"], description=fields["description"], kicker=kicker,
        heading=fields.get("heading", ""),
        body=markdown(root, item.body, out, item.path), crumbs=crumbs, og_type="article",
        jsonld=[article], head_extra=head_extra, meta_line=meta_line, after="\n".join(after),
        backlink=(href(out, f"{app.dir}/{key}/"), section.back), generator=_generator(item), **social)
    return render_page(root, page)


def _check_site_module():
    return _load("check_site", "check-site.py")


def html_pages(root: Path) -> List[str]:
    exempt = _check_site_module().EXEMPT_DIRS
    pages = []
    for file in root.rglob("*.html"):
        rel = file.relative_to(root).as_posix()
        if ".git" in file.relative_to(root).parts or any(rel.startswith(d + "/") for d in exempt):
            continue
        pages.append(rel)
    return sorted(pages)


def is_generated(text: str) -> bool:
    return f"<!-- {GENERATED} from " in text


def sitemap(pages: Dict[str, str], lastmod: Dict[str, str]) -> str:
    rows = []
    for url, path in sorted((url_for(path), path) for path, text in pages.items()
                            if 'name="robots" content="noindex"' not in text):
        stamp = f"<lastmod>{lastmod[path]}</lastmod>" if path in lastmod else ""
        rows.append(f"  <url><loc>{url}</loc>{stamp}</url>")
    return ('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            + "\n".join(rows) + "\n</urlset>\n")


ROBOTS = f"User-agent: *\nAllow: /\n\nSitemap: {ORIGIN}/sitemap.xml\n"


def build_site(root: Path) -> Dict[str, str]:
    """Every file the build owns, from the site root, with the content it should have."""
    out: Dict[str, str] = {}
    lastmod: Dict[str, str] = {}
    for app in APPS.values():
        indexes, pages = read_sources(root, app)
        for key in app.sections:
            for item in pages[key]:
                out[item.out] = content_page(root, key, item, pages[key])
                lastmod[item.out] = item.fields.get("updated", item.fields["date"])
            if key in indexes:
                out[indexes[key].out] = section_page(root, key, indexes[key], pages[key])
    everything: Dict[str, str] = {}
    for rel in html_pages(root):
        if rel in out:
            continue
        text = (root / rel).read_text(encoding="utf-8")
        if in_app(rel) and is_generated(text):
            continue  # a page whose source is gone: stale(), and write() removes it
        if in_app(rel):
            refreshed = with_stylesheet(with_subnav(text, rel), rel)
            if refreshed != text:
                out[rel] = refreshed
            text = refreshed
        everything[rel] = text
    everything.update({path: text for path, text in out.items() if path.endswith(".html")})
    out["sitemap.xml"] = sitemap(everything, lastmod)
    out["robots.txt"] = ROBOTS
    return out


def in_app(rel: str) -> bool:
    """Whether a page is one of an app's (under apps/<key>/ for an app in APPS)."""
    return any(rel.startswith(app.dir + "/") for app in APPS.values())


def stale(root: Path, expected: Dict[str, str]) -> List[str]:
    return [rel for rel in html_pages(root) if in_app(rel) and rel not in expected
            and is_generated((root / rel).read_text(encoding="utf-8"))]


def check(root: Path) -> List[str]:
    try:
        expected = build_site(root)
    except BuildError as error:
        return [f"the build stops: {error}"]
    problems = []
    for rel, text in sorted(expected.items()):
        file = root / rel
        if not file.is_file():
            problems.append(f"{rel} is missing; run python3 tools/dayfolio-build.py")
        elif file.read_text(encoding="utf-8") != text:
            problems.append(f"{rel} differs from what the build makes; run python3 tools/dayfolio-build.py")
    for rel in stale(root, expected):
        problems.append(f"{rel} was generated from a source that is gone; run python3 tools/dayfolio-build.py")
    return problems


def write(root: Path) -> List[str]:
    expected = build_site(root)
    changed = []
    for rel, text in sorted(expected.items()):
        file = root / rel
        if not file.is_file() or file.read_text(encoding="utf-8") != text:
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_text(text, encoding="utf-8")
            changed.append(rel)
    for rel in stale(root, expected):
        file = root / rel
        file.unlink()
        if not any(file.parent.iterdir()):
            file.parent.rmdir()
        changed.append(f"{rel} (removed)")
    return changed


def main(argv: Optional[List[str]] = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    if args == ["--check"]:
        problems = check(ROOT)
        for problem in problems:
            print(f"  · {problem}")
        print("FAIL — the committed pages differ from the build." if problems else "OK — every page matches its source.")
        return 1 if problems else 0
    if args:
        print(__doc__)
        return 2
    try:
        changed = write(ROOT)
    except BuildError as error:
        print(f"FAIL — {error}")
        return 1
    for rel in changed:
        print(f"wrote {rel}")
    print(f"OK — {len(changed)} file(s) changed." if changed else "OK — nothing to change.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
