def owned(root: Path) -> List[str]:
    folder = root / OUT
    return sorted(p.relative_to(root).as_posix() for p in folder.rglob("*.html")
                  if f"<!-- {GENERATED} from " in p.read_text(encoding="utf-8")) if folder.is_dir() else []


def check(root: Path) -> List[str]:
    if not (root / CATALOG).is_file() and not owned(root):
        return []  # a site without the gallery (the build's own test fixture)
    try:
        expected = build(root)
    except CatalogError as error:
        return [f"the generator stops: {error}"]
    problems = []
    for rel, text in sorted(expected.items()):
        file = root / rel
        if not file.is_file():
            problems.append(f"{rel} is missing; run python3 tools/diagrove-templates.py")
        elif file.read_text(encoding="utf-8") != text:
            problems.append(f"{rel} differs from what the catalogue makes; run python3 tools/diagrove-templates.py")
    for rel in owned(root):
        if rel not in expected:
            problems.append(f"{rel} is for a template or category the catalogue no longer has; "
                            "run python3 tools/diagrove-templates.py")
    return problems


def write(root: Path) -> List[str]:
    expected = build(root)
    changed = []
    for rel, text in sorted(expected.items()):
        file = root / rel
        if not file.is_file() or file.read_text(encoding="utf-8") != text:
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_text(text, encoding="utf-8")
            changed.append(rel)
    for rel in owned(root):
        if rel not in expected:
            file = root / rel
            file.unlink()
            folder = file.parent
            while folder != root / OUT and not any(folder.iterdir()):
                folder.rmdir()
                folder = folder.parent
            changed.append(f"{rel} (removed)")
    return changed


# ----- the app: its templates, words and pictures -----

def has_pillow() -> bool:
    return importlib.util.find_spec("PIL") is not None


def search_words(strings: dict) -> Dict[str, List[str]]:
    """Each template's gallery search words, from the app's String Catalog: the British English value where there
    is one, as the site spells, else the source."""
    words: Dict[str, List[str]] = {}
    for key, entry in strings.get("strings", {}).items():
        found = re.match(r"Search words for the template (\w+),", entry.get("comment", ""))
        if not found:
            continue
        local = entry.get("localizations", {})
        value = (local.get("en-GB") or local.get("en") or {}).get("stringUnit", {}).get("value", key)
        words[found.group(1)] = [w.strip() for w in value.split(",") if w.strip()]
    return words


def contents(text: str, inspect: dict, stencils: Dict[str, dict]) -> dict:
    """What is in a template, from its Diagrove text and `diagrove inspect`: its canvases (name, size, projection,
    layers), the stencils it uses in the order it first uses them, its lines with both ends attached, and whether it
    plays (an on-click) or follows data (a bind)."""
    projections = {}
    for chunk in re.split(r'(?m)^(?=canvas ")', text):
        named = re.match(r'canvas "((?:[^"\\]|\\.)*)"', chunk)
        if named:
            projections[named.group(1)] = "isometric" if re.search(r"(?m)^\s*projection:\s*isometric", chunk) else "flat"
    canvases = [{"name": c["name"], "size": c["size"], "projection": projections.get(c["name"], "flat"),
                 "layers": [layer["name"] for layer in c.get("layers", [])]} for c in inspect["canvases"]]
    used: List[dict] = []
    for sid in re.findall(r"\bstencil:\s*([\w.-]+)", text):
        if sid not in stencils:
            raise CatalogError(f"the stencil {sid} is not one diagrove stencils list names")
        if all(s["id"] != sid for s in used):
            s = stencils[sid]
            used.append({"id": sid, "name": s["name"], "library": s["library"]})
    def attached(end) -> bool:
        return isinstance(end, str) and not end.startswith("(")
    connections = sum(1 for c in inspect["canvases"] for g in c.get("graphics", [])
                      if g.get("kind") == "line" and attached(g.get("from")) and attached(g.get("to")))
    return {"canvases": canvases, "stencils": used, "connections": connections,
            "plays": bool(re.search(r"\bon-click:", text)), "binds": bool(re.search(r"(?m)(^|[{;]\s*)bind\s", text))}


def _run(cli: Path, *args: str) -> dict:
    done = subprocess.run([str(cli), *args], capture_output=True, text=True)
    try:
        answer = json.loads(done.stdout)
    except json.JSONDecodeError:
        raise CatalogError(f"{cli} {' '.join(args)}: no JSON answer ({done.stderr.strip()[:200]})") from None
    if not answer.get("ok"):
        raise CatalogError(f"{cli} {' '.join(args)}: {answer.get('errors')}")
    return answer


def _webp(png: Path, target: Path, width: Optional[int] = None, quality: int = PICTURE_QUALITY) -> None:
    from PIL import Image  # the picture step's one dependency
    with Image.open(png) as image:
        picture = image.convert("RGB")  # the paper is opaque: no alpha, so it reads as a figure, not a window
    if width and picture.width > width:
        picture = picture.resize((width, round(picture.height * width / picture.width)), Image.LANCZOS)
    data = io.BytesIO()
    picture.save(data, "WEBP", quality=quality, method=6)
    target.parent.mkdir(parents=True, exist_ok=True)
    if not target.is_file() or target.read_bytes() != data.getvalue():
        target.write_bytes(data.getvalue())


def sync(root: Path, app, cli) -> List[str]:
    """Read the app's templates through its command-line tool, draw their pictures, and write the catalogue."""
    if not has_pillow():
        raise CatalogError("the --app step makes WebP pictures with Pillow: python3 -m pip install Pillow")
    app, cli = Path(app).expanduser(), Path(cli).expanduser()
    strings_file = app / APP_STRINGS
    if not strings_file.is_file():
        raise CatalogError(f"{app}: not the Diagrove repository (no {APP_STRINGS})")
    words = search_words(json.loads(strings_file.read_text(encoding="utf-8")))
    listed = _run(cli, "templates", "list", "--quiet")["templates"]
    stencils = {s["id"]: s for s in _run(cli, "stencils", "list", "--quiet")["stencils"]}
    version = subprocess.run([str(cli), "--version"], capture_output=True, text=True).stdout.strip()
    categories: List[dict] = []
    entries: List[dict] = []
    kept = set()
    scratch = Path(tempfile.mkdtemp(prefix="diagrove-templates-"))
    try:
        for item in listed:
            if all(c["id"] != item["category"] for c in categories):
                categories.append({"id": item["category"], "name": item["categoryName"]})
            docs = {}
            for paper, word, _ in PAPERS:
                docs[word] = scratch / f"{item['id']}-{word}.diagrove"
                _run(cli, "new", "--template", item["id"], "--paper", paper, "-o", str(docs[word]), "--quiet")
            facts = contents(_run(cli, "text", str(docs["white"]), "--quiet")["text"],
                             _run(cli, "inspect", str(docs["white"]), "--quiet")["document"], stencils)
            entry = {"id": item["id"], "name": item["name"], "summary": item["description"],
                     "category": item["category"], "blank": item["blank"], "isometric": item["isometric"],
                     "searchWords": words.get(item["id"], []), **facts}
            entries.append(entry)
            if item["blank"]:
                continue
            template = Template(entry["id"], entry["name"], entry["summary"], entry["category"], False,
                                 entry["isometric"], [], entry["canvases"], [], 0, False, False)
            folder = root / OUT / slug(item["categoryName"]) / template.slug
            for paper, word, _ in PAPERS:
                for n, name in enumerate(template.pictures(word), 1):
                    png = scratch / f"{item['id']}-{word}-{n}.png"
                    _run(cli, "render", str(docs[word]), "--canvas", str(n), "--scale", "2", "-o", str(png), "--quiet")
                    _webp(png, folder / name)
                    kept.add(folder / name)
                    if word == "white" and n == 1:
                        _webp(png, folder / template.card, CARD_WIDTH, CARD_QUALITY)
                        kept.add(folder / template.card)
    finally:
        shutil.rmtree(scratch, ignore_errors=True)
    catalog = {"formatVersion": FORMAT_VERSION,
               "source": f"diagrove {version}: the app’s own templates, read with --app (British English)",
               "categories": categories, "templates": entries}
    text = json.dumps(catalog, ensure_ascii=False, indent=2) + "\n"
    target = root / CATALOG
    target.parent.mkdir(parents=True, exist_ok=True)
    changed = []
    if not target.is_file() or target.read_text(encoding="utf-8") != text:
        target.write_text(text, encoding="utf-8")
        changed.append(CATALOG)
    for picture in sorted((root / OUT).rglob("*.webp")) if (root / OUT).is_dir() else []:
        if picture not in kept:
            picture.unlink()
            changed.append(f"{picture.relative_to(root).as_posix()} (removed)")
    return changed


def main(argv: Optional[List[str]] = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    checking = "--check" in args
    if checking:
        args.remove("--check")
    options = {}
    for flag in ("--app", "--cli"):
        if flag in args:
            at = args.index(flag)
            if at + 1 >= len(args):
                print(__doc__)
                return 2
            options[flag] = args[at + 1]
            del args[at:at + 2]
    if args or (checking and options) or (len(options) == 1):
        print(__doc__)
        return 2
    if checking:
        problems = check(ROOT)
        for problem in problems:
            print(f"  · {problem}")
        print("FAIL — the template pages differ from the catalogue." if problems
              else "OK — every template page matches the catalogue.")
        return 1 if problems else 0
    try:
        synced = sync(ROOT, options["--app"], options["--cli"]) if options else []
        changed = write(ROOT)
        catalog = load(ROOT)
    except CatalogError as error:
        print(f"FAIL — {error}")
        return 1
    for rel in synced + changed:
        print(f"wrote {rel}")
    print(f"OK — {len(catalog.templates)} templates in {len(catalog.categories)} categories; "
          f"{len(synced) + len(changed)} file(s) changed.")
    if changed:
        print("Next: python3 tools/dayfolio-build.py, then python3 tools/check-site.py.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
