#!/usr/bin/env python3
"""Generate Diagrove's template gallery from the app's own templates.

    python3 tools/diagrove-templates.py                                     # write the gallery
    python3 tools/diagrove-templates.py --app /path/to/diagrove --cli /path/to/diagrove-cli
                                                                            # read the app's templates and draw
                                                                            # their pictures, then write
    python3 tools/diagrove-templates.py --check                             # write nothing; fail on a difference

Diagrove's templates are Diagrove text in the app's Swift package, so the app's command-line tool is how this
site reads them. --app asks the tool (--cli, built from the Diagrove repository; README, Diagrove template
gallery, says how) for every template in the gallery's order (`diagrove templates list`), makes each on White
and on Ink paper (`diagrove new --template`), reads what is in it (`diagrove text`, `diagrove inspect`, the
names of its stencils from `diagrove stencils list`) and draws every canvas of it (`diagrove render`). The
gallery's search words come from the app's String Catalog, in British English as the site writes. It keeps
that in content/diagrove/templates/catalog.json, and the pictures as WebP beside the pages, so the site can be
checked and rebuilt without the app. That step needs Pillow, for WebP; the rest is standard library only.

From the catalogue and the site's own words on each template and category (content/diagrove/templates/
notes.json: what it is for, and the words people search for when a page should be titled by them), this writes,
through tools/dayfolio-build.py's shell:

    apps/diagrove/templates/                         the gallery, every category in the app's order
    apps/diagrove/templates/<category>/              a page per category, a card with a picture per template
    apps/diagrove/templates/<category>/<template>/   a page per template: its pictures on both papers, what it
                                                     is for, what is in it and how to start from it

The generator stops, naming the file, at a catalogue it cannot trust, a template or category without the site's
words, words against the site's copy rules, or a missing picture. A page whose template left the catalogue is
removed. GitHub Pages serves files, so the pages are committed, and tools/check-site.py runs --check.
"""

