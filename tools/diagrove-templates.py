GUIDE_CLI = f"{APP}/guide/command-line-tool/"
NUMBERS = ("no", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten")


class CatalogError(Exception):
    """A catalogue, notes or pictures the generator will not guess about; the message names the file."""


def _load(name: str, file: str):
    """Another tool in this folder, as a module (once: dataclasses need it in sys.modules)."""
    if name not in sys.modules:
        spec = importlib.util.spec_from_file_location(name, Path(__file__).with_name(file))
        module = importlib.util.module_from_spec(spec)
        sys.modules[name] = module
        spec.loader.exec_module(module)
    return sys.modules[name]


def _build():
    return _load("dayfolio_build", "dayfolio-build.py")


def _archive():
    return _load("archive_page", "archive-page.py")


def slug(name: str) -> str:
    """A name as an address: lowercase words joined by hyphens ("CI/CD pipeline" is ci-cd-pipeline)."""
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def number(n: int) -> str:
    return NUMBERS[n] if n < len(NUMBERS) else str(n)


def listing(words: List[str]) -> str:
    return words[0] if len(words) == 1 else ", ".join(words[:-1]) + " and " + words[-1] if words else ""


def plural(n: int, one: str, many: str) -> str:
    return f"{number(n) if n < 10 else n} {one if n == 1 else many}"


# ----- the catalogue -----

@dataclass
class Category:
    id: str
    name: str
    summary: str = ""

    @property
    def slug(self) -> str:
        return slug(self.name)


@dataclass
class Template:
    id: str
    name: str
    summary: str
    category: str
    blank: bool
    isometric: bool
    search_words: List[str]
    canvases: List[dict]
    stencils: List[dict]
    connections: int
    plays: bool
    binds: bool
    use: str = ""                 # the site's words: what it is for
    page_title: str = ""          # the site's words: what people search for, when it differs from the name

    @property
    def slug(self) -> str:
        return slug(self.name)

    def pictures(self, word: str) -> List[str]:
        """Its pictures on one paper, a canvas each: flowchart-white.webp, then app-screen-white-2.webp."""
        return [f"{self.slug}-{word}{'' if n == 1 else f'-{n}'}.webp" for n in range(1, len(self.canvases) + 1)]

    @property
    def card(self) -> str:
        return f"{self.slug}-card.webp"


@dataclass
class Catalog:
    source: str
    categories: List[Category]
    templates: Dict[str, Template] = field(default_factory=dict)

    def listed(self, category: str) -> List[Template]:
        return [t for t in self.templates.values() if t.category == category]

    def category(self, template: Template) -> Category:
        return next(c for c in self.categories if c.id == template.category)

    @property
    def designed(self) -> List[Template]:
        return [t for t in self.templates.values() if not t.blank]


def _need(data: dict, key: str, kind, where: str):
    if key not in data:
        raise CatalogError(f"{where}: needs “{key}”")
    if not isinstance(data[key], kind):
        raise CatalogError(f"{where}: “{key}” is not a {getattr(kind, '__name__', kind)}")
    return data[key]


def load_catalog(root: Path) -> Catalog:
    where = CATALOG
    try:
        data = json.loads((root / CATALOG).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise CatalogError(f"{where}: {error}") from None
    if data.get("formatVersion") != FORMAT_VERSION:
        raise CatalogError(f"{where}: formatVersion is {data.get('formatVersion')!r}; this generator reads "
                           f"{FORMAT_VERSION}")
    categories = [Category(_need(c, "id", str, where), _need(c, "name", str, where))
                  for c in _need(data, "categories", list, where)]
    known = {c.id for c in categories}
    catalog = Catalog(_need(data, "source", str, where), categories)
    for item in _need(data, "templates", list, where):
        tid = _need(item, "id", str, where)
        here = f"{where}: {tid}"
        if tid in catalog.templates:
            raise CatalogError(f"{here}: listed twice")
        category = _need(item, "category", str, here)
        if category not in known:
            raise CatalogError(f"{here}: its category “{category}” is not among the catalogue’s categories")
        catalog.templates[tid] = Template(
            id=tid, name=_need(item, "name", str, here), summary=_need(item, "summary", str, here),
            category=category, blank=_need(item, "blank", bool, here), isometric=_need(item, "isometric", bool, here),
            search_words=_need(item, "searchWords", list, here), canvases=_need(item, "canvases", list, here),
            stencils=_need(item, "stencils", list, here), connections=_need(item, "connections", int, here),
            plays=_need(item, "plays", bool, here), binds=_need(item, "binds", bool, here))
        if not catalog.templates[tid].canvases:
            raise CatalogError(f"{here}: has no canvas")
    seen: Dict[str, str] = {}
    for t in catalog.templates.values():
        key = (t.category, t.slug)
        if key in seen:
            raise CatalogError(f"{where}: {t.id} and {seen[key]} would share the address {t.slug}")
        seen[key] = t.id
    for c in categories:
        if not catalog.listed(c.id):
            raise CatalogError(f"{where}: the category {c.id} holds no template")
    return catalog


def load_notes(root: Path, catalog: Catalog) -> Catalog:
    """The site's words on each template and category, checked against the copy rules, on the catalogue."""
    build = _build()
    where = NOTES
    try:
        text = (root / NOTES).read_text(encoding="utf-8")
        data = json.loads(text)
    except (OSError, json.JSONDecodeError) as error:
        raise CatalogError(f"{where}: {error}") from None
    notes, categories = _need(data, "templates", dict, where), _need(data, "categories", dict, where)
    words = [(f"categories.{k}", v) for k, v in categories.items()] + [
        (f"templates.{k}.{name}", v) for k, note in notes.items() if isinstance(note, dict) for name, v in note.items()]
    problems = [problem for key, value in words if isinstance(value, str)
                for problem in build.lint_copy(value, f"{where}: {key}")]
    if problems:
        raise CatalogError("\n".join(problems))
    for key in sorted(set(notes) - set(catalog.templates)):
        raise CatalogError(f"{where}: a note for the template {key}, which the app does not have")
    for key in sorted(set(categories) - {c.id for c in catalog.categories}):
        raise CatalogError(f"{where}: a note for the category {key}, which the app does not have")
    for c in catalog.categories:
        if not isinstance(categories.get(c.id), str) or not categories[c.id].strip():
            raise CatalogError(f"{where}: the category {c.id} needs a line on what its templates are for")
        c.summary = categories[c.id]
    for t in catalog.templates.values():
        note = notes.get(t.id)
        if not isinstance(note, dict) or not str(note.get("for", "")).strip():
            raise CatalogError(f"{where}: the template {t.id} needs “for”: what it is for, in the site’s words")
        t.use, t.page_title = note["for"], note.get("page_title", "")
    return catalog


def load(root: Path) -> Catalog:
    catalog = load_notes(root, load_catalog(root))
    titles: Dict[str, str] = {}
    build = _build()
    for t in catalog.templates.values():
        title = title_of(t)
        if len(title) > build.TITLE_MAX:
            raise CatalogError(f"{NOTES}: {t.id}: the page title “{title}” is over {build.TITLE_MAX} characters")
        if title.lower() in titles:
            raise CatalogError(f"{NOTES}: {t.id}: the page title “{title}” is already {titles[title.lower()]}’s")
        titles[title.lower()] = t.id
    for t in catalog.designed:
        folder = root / _dir(page_path(catalog, t))
        for name in [*t.pictures("white"), *t.pictures("ink"), t.card]:
            if not (folder / name).is_file():
                raise CatalogError(f"{_dir(page_path(catalog, t))}{name} is missing; run python3 "
                                   "tools/diagrove-templates.py --app /path/to/diagrove --cli /path/to/diagrove-cli")
    return catalog


# ----- pages -----

def category_path(category: Category) -> str:
    return f"{OUT}/{category.slug}/index.html"


def page_path(catalog: Catalog, template: Template) -> str:
    return f"{OUT}/{catalog.category(template).slug}/{template.slug}/index.html"


def _dir(path: str) -> str:
    return path.rsplit("/", 1)[0] + "/"


def title_of(template: Template) -> str:
    return template.page_title or f"{template.name} template"


def _esc(text: str) -> str:
    return _build().esc(text)


def _inline(page: str, text: str) -> str:
    """The site's words as HTML: `code`, **strong**, and links to pages of Diagrove's (from apps/diagrove/)."""
    build = _build()
    return _archive().inline(text, link=lambda label, url: f'<a href="{build.href(page, f"{APP}/{url}")}">{label}</a>')


def describe(where: str, *candidates: str) -> str:
    """The first candidate that fits a search result (50–160 characters)."""
    build = _build()
    for text in candidates:
        if build.DESCRIPTION_MIN <= len(text) <= build.DESCRIPTION_MAX:
            return text
    raise CatalogError(f"{where}: no description fits {build.DESCRIPTION_MIN}–{build.DESCRIPTION_MAX} characters")


def _crumbs(page: str, crumbs: List[Tuple[str, str]]) -> str:
    build = _build()
    trail = '<span class="crumbs-sep" aria-hidden="true">/</span>'.join(
        f'<a href="{build.href(page, path)}">{_esc(name)}</a>' for name, path in crumbs)
    return f'<nav class="crumbs" aria-label="Breadcrumb">{trail}</nav>'


def _item_list(items: List[Tuple[str, str]]) -> dict:
    build = _build()
    return {"@context": "https://schema.org", "@type": "ItemList", "itemListElement": [
        {"@type": "ListItem", "position": n, "url": build.url_for(path), "name": name}
        for n, (name, path) in enumerate(items, 1)]}


def _base_crumbs() -> List[Tuple[str, str]]:
    return [("Diagrove", f"{APP}/"), ("Templates", f"{OUT}/")]


def _generator(*sources: str) -> str:
    return f"{GENERATED} from {' and '.join(sources)}: run the tool, never edit this page."


def _size(root: Path, folder: str, name: str) -> Tuple[int, int]:
    return _build().image_size(root / folder / name)


def _figures(root: Path, catalog: Catalog, t: Template) -> str:
    folder = _dir(page_path(catalog, t))
    parts, first = [], True
    for _, word, paper in PAPERS:
        for name, canvas in zip(t.pictures(word), t.canvases):
            width, height = _size(root, folder, name)
            many = len(t.canvases) > 1
            alt = (f"The {t.name} template on {paper} paper" + (f", its {canvas['name']} canvas" if many else "")
                   + f", as Diagrove draws it: {t.summary[0].lower() + t.summary[1:]}.")
            caption = f"On {paper} paper" + (f": {canvas['name']}" if many else "")
            lazy = "" if first else ' loading="lazy"'
            first = False
            parts.append(f'<figure class="figure figure-landscape figure-wide tpl-shot"><img src="{name}" '
                         f'alt="{_esc(alt)}" width="{width}" height="{height}"{lazy} decoding="async">'
                         f"<figcaption>{_esc(caption)}</figcaption></figure>")
    return "\n".join(parts)


def _canvas_text(t: Template) -> str:
    sizes = {tuple(c["size"]) for c in t.canvases}
    def size(c):
        return f"{c['size'][0]:g} × {c['size'][1]:g} points"
    if len(t.canvases) == 1:
        c = t.canvases[0]
        text = f"One canvas, {_esc(c['name'])}, {size(c)}"
    else:
        names = listing([_esc(c["name"]) for c in t.canvases])
        text = (f"{number(len(t.canvases)).capitalize()} canvases, {names}"
                + (f", each {size(t.canvases[0])}" if len(sizes) == 1 else ""))
    layers = [c["layers"] for c in t.canvases]
    if all(layers):
        if all(ls == layers[0] for ls in layers):
            text += (f". Its graphics are on {plural(len(layers[0]), 'layer', 'layers')}, "
                     f"{listing([_esc(n) for n in layers[0]])}" if len(layers[0]) > 1
                     else f", on one layer, {_esc(layers[0][0])}")
        else:
            text += ". " + " ".join(f"{_esc(c['name'])} has the layers {listing([_esc(n) for n in c['layers']])}."
                                    for c in t.canvases).rstrip(".")
    return text + "."


def _stencil_text(t: Template) -> str:
    if not t.stencils:
        return ""
    shown = t.stencils[:STENCILS_LISTED]
    libraries: Dict[str, List[str]] = {}
    for s in shown:
        libraries.setdefault(s["library"], []).append(_esc(s["name"]))
    parts = [f"{listing(names)} from the {_esc(library)} library" for library, names in libraries.items()]
    more = len(t.stencils) - len(shown)
    tail = f", and {more} more" if more else ""
    return (f"<p>It’s drawn with {plural(len(t.stencils), 'stencil', 'stencils')}: {'; '.join(parts)}{tail}. "
            "A stencil recolours whole with one tint, so you can change its colour without redrawing it.</p>")


def _contents(page: str, t: Template) -> List[str]:
    build = _build()
    href = lambda target: build.href(page, target)  # noqa: E731
    body = [f"<p>{_canvas_text(t)}</p>"]
    if t.isometric:
        body.append("<p>It’s an isometric canvas: its grid runs along three axes, and things stand on the floor or "
                    "against a wall, at their own height, with Diagrove working out which is in front. "
                    f'<a href="{href(GUIDE_ISOMETRIC)}">Isometric canvases</a>, in the guide, explains them.</p>')
    stencils = _stencil_text(t)
    if stencils:
        body.append(stencils)
    if t.connections:
        lines = ("One connected line joins two of its shapes" if t.connections == 1 else
                 f"{plural(t.connections, 'connected line', 'connected lines').capitalize()} join its shapes")
        body.append(f"<p>{lines}, attached to their magnets, so {'it follows' if t.connections == 1 else 'they follow'} "
                    "when you move a shape.</p>")
    if t.plays:
        body.append("<p>It plays. Choose <strong>Play</strong> in the toolbar (Option-Command-P on the Mac) and click "
                    "or tap through it as you would an app; press Esc, or tap Stop on iPad, to go back to editing. "
                    f'<a href="{href(GUIDE_PLAY)}">Play mode and actions</a> says how to add your own.</p>')
    if t.binds:
        body.append("<p>Some of its words or colours follow data, through bindings. "
                    f'<a href="{href(GUIDE_BINDINGS)}">Bindings</a>, in the guide, explains them.</p>')
    body.append("<p>Everything in it is ordinary Diagrove, in palette colours: change the words, move things, retint "
                "a stencil, delete what you don’t need, or ask the prompt bar for a change.</p>")
    return body


def _start(page: str, catalog: Catalog, t: Template) -> List[str]:
    build = _build()
    href = lambda target: build.href(page, target)  # noqa: E731
    category = catalog.category(t)
    name = _esc(t.name)
    words = [f"“{_esc(w)}”" for w in t.search_words[:3]]
    find = f" or search for {words[0]}" if words else ""
    steps = [
        "<ol>",
        "<li>On the Mac, choose <strong>File › New from template…</strong> (Shift-Command-N). On iPad, choose "
        "<strong>Choose a template</strong> on the start screen.</li>",
        f"<li>Choose <strong>{_esc(category.name)}</strong> in the gallery’s sidebar{find}, and find {name}.</li>",
        "<li>Choose White or Ink at <strong>Paper</strong>. On the Mac, double-click the template, or select it and "
        "click <strong>Create</strong>; on iPad, tap it.</li>",
        "</ol>",
        f"<p>A new document opens, named “{name}”, then “{name} 2” for the next. It has no history to undo, so you "
        "start clean. On iPad it’s saved as a file straight away.</p>",
    ]
    if t.search_words:
        steps.append(f"<p>The gallery’s search finds it by its name and its line, and also by "
                     f"{listing([f'“{_esc(w)}”' for w in t.search_words])}.</p>")
    if t.blank:
        steps.append("<p>On the Mac, <strong>File › New diagram</strong> (Command-N) and <strong>New isometric "
                     "diagram</strong> make the blank ones straight away.</p>")
    steps.append(f"<p>From Terminal, with the <code>diagrove</code> command-line tool:</p>\n<pre><code>"
                 f"diagrove new --template {t.id} -o {t.slug}.diagrove\n"
                 f"diagrove new --template {t.id} --paper dark -o {t.slug}-ink.diagrove</code></pre>\n"
                 f'<p><a href="{href(GUIDE_CLI)}">The command-line tool</a>, in the guide, says how to install it.</p>')
    return steps


def template_page(root: Path, catalog: Catalog, t: Template) -> str:
    build = _build()
    out = page_path(catalog, t)
    category = catalog.category(t)
    href = lambda target: build.href(out, target)  # noqa: E731
    facts = [("CATEGORY", f'<a href="{href(_dir(category_path(category)))}">{_esc(category.name)}</a>'),
             ("PAPER", "White or Ink"),
             ("CANVAS" if len(t.canvases) == 1 else "CANVASES",
              ", ".join(_esc(c["name"]) for c in t.canvases)),
             ("PROJECTION", "Isometric" if t.isometric else "Flat")]
    if t.stencils:
        facts.append(("STENCILS", str(len(t.stencils))))
    if t.plays:
        facts.append(("PLAYS", "Yes, in Play mode"))
    body = [f"<p>{_esc(t.summary)}.</p>",
            f"<p>{_inline(out, t.use)}</p>",
            '<dl class="facts tpl-facts">' + "".join(f"<div><dt>{k}</dt><dd>{v}</dd></div>" for k, v in facts) + "</dl>"]
    if t.blank:
        body.append("<p>There’s nothing to show: the canvas is empty"
                    + (", with an isometric grid to draw on." if t.isometric else ", ready for your first shape.")
                    + "</p>")
    else:
        body += ['<h2 id="pictures">What it looks like</h2>',
                 "<p>Diagrove’s own drawing of the template, on both papers. Every template comes on White or Ink "
                 "paper; a document keeps its paper in light and dark appearance.</p>",
                 _figures(root, catalog, t)]
    body += ['<h2 id="contents">What’s in it</h2>', *_contents(out, t),
             '<h2 id="start">Start a diagram from it</h2>', *_start(out, catalog, t),
             f'<p>More about the gallery, your own templates and the papers in '
             f'<a href="{href(GUIDE_TEMPLATES)}">Templates</a>, in the guide.</p>']
    related = [r for r in catalog.listed(t.category) if r.id != t.id]
    if related:
        body.append(f'<h2 id="related">More {_esc(category.name.lower() if category.name != "Blank" else "blank")} '
                    "templates</h2>")
        body.append('<ul class="tpl-related">' + "".join(
            f'<li><a href="{href(_dir(page_path(catalog, r)))}">{_esc(r.name)}</a>: {_esc(r.summary)}.</li>'
            for r in related) + "</ul>")
    crumbs = _base_crumbs() + [(category.name, _dir(category_path(category)))]
    summary = t.summary
    description = describe(out, f"{summary}. The {t.name} template in Diagrove for Mac and iPad, on White or Ink "
                                "paper, and how to start a diagram from it.",
                           f"{summary}. The {t.name} template in Diagrove, on White or Ink paper.",
                           f"{summary}. A template in Diagrove for Mac and iPad.")
    page = build.Page(
        path=out, title=title_of(t), description=description, kicker=_crumbs(out, crumbs),
        body="\n".join(body), crumbs=crumbs + [(t.name, out)],
        after=build._app_box(out), backlink=(href(_dir(category_path(category))), f"{category.name} templates"),
        generator=_generator(CATALOG, NOTES))
    return _shell(out, build.render_page(root, page))


def _card(root: Path, catalog: Catalog, page: str, t: Template) -> str:
    build = _build()
    folder = _dir(page_path(catalog, t))
    link = build.href(page, folder)
    art = ""
    if not t.blank:
        width, height = _size(root, folder, t.card)
        art = (f'\n      <img src="{link}{t.card}" alt="{_esc(t.name)} on White paper" width="{width}" '
               f'height="{height}" loading="lazy">')
    tags = [w for w, on in (("ISOMETRIC", t.isometric), ("PLAYS", t.plays)) if on]
    tag = f'\n      <span class="tag">{" · ".join(tags)}</span>' if tags else ""
    return (f'    <a class="card tpl-card" href="{link}">{art}{tag}\n      <h3>{_esc(t.name)}</h3>\n'
            f"      <p>{_esc(t.summary)}.</p>\n    </a>")


def category_page(root: Path, catalog: Catalog, category: Category) -> str:
    build = _build()
    out = category_path(category)
    listed = catalog.listed(category.id)
    href = lambda target: build.href(out, target)  # noqa: E731
